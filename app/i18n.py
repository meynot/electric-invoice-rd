def normalize_languages(codes: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for raw in codes:
        code = raw.strip().lower()
        if not code or code in seen:
            continue
        seen.add(code)
        result.append(code)
    return result or ["en"]


def language_options(codes: list[str]) -> list[dict[str, str]]:
    options = []
    for code in normalize_languages(codes):
        options.append(
            {
                "code": code,
                "label": LANGUAGE_LABELS.get(code, code.upper()),
            }
        )
    return options


def translations_for(codes: list[str]) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for code in normalize_languages(codes):
        out[code] = _TRANSLATIONS.get(code, _EN)
    return out


def default_language(codes: list[str]) -> str:
    return normalize_languages(codes)[0]
